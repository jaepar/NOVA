CREATE TABLE IF NOT EXISTS job_translation (
    job_translation_id BIGINT NOT NULL AUTO_INCREMENT,
    job_id BIGINT NOT NULL,
    language VARCHAR(10) NOT NULL,
    company VARCHAR(100),
    region VARCHAR(100),
    opening_title VARCHAR(100),
    job_category VARCHAR(50),
    experience VARCHAR(50),
    salary VARCHAR(50),
    deadline_type VARCHAR(50),
    recruit_count VARCHAR(50),
    preferred VARCHAR(100),
    age VARCHAR(50),
    gender VARCHAR(50),
    job_role VARCHAR(50),
    work_period VARCHAR(50),
    employment_type VARCHAR(50),
    benefits VARCHAR(100),
    address VARCHAR(255),
    introduce TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (job_translation_id),
    UNIQUE KEY uk_job_translation_job_language (job_id, language),
    CONSTRAINT fk_job_translation_job FOREIGN KEY (job_id) REFERENCES job (job_id)
);

